"""
Workflow: Soil Texture raster (categorical) + property lookup table
          -> per-property continuous grids at 250m resolution, as .asc files

Input files:
  - Soil_Texture.tif                      (categorical raster, 30m, EPSG:32643)
  - soil_params_xlsx_-_soil_texture.csv   (lookup table: texture name -> properties)

Steps:
  1. Reclassify texture raster -> one continuous raster per property (native 30m res)
  2. Aggregate each property raster to 250m
       - arithmetic mean for most properties
       - geometric mean (log-average) for ksat, since it spans orders of magnitude
  3. Write each 250m raster out as an ESRI ASCII grid (.asc)

Requires: rasterio, numpy, pandas
    pip install rasterio numpy pandas --break-system-packages
"""

import rasterio
from rasterio.warp import reproject, Resampling
import numpy as np
import pandas as pd
import os

# ----------------------------------------------------------------------
# CONFIG
# ----------------------------------------------------------------------

TEXTURE_TIF = "/content/Soil_Texture.tif"
LUT_CSV = "/content/soil_params.xlsx - soil_texture.csv"
WORK_DIR = "/content/work"
OUT_DIR = "/content/output"
os.makedirs(WORK_DIR, exist_ok=True)
os.makedirs(OUT_DIR, exist_ok=True)

NODATA = -99999

# --- Target grid definition (MUST match DRYP's other input .asc files exactly:
#     mask, DEM, etc. All DRYP inputs need identical ncols/nrows/corner/cellsize) ---
TARGET_NCOLS = 156
TARGET_NROWS = 105
TARGET_XLLCORNER = 798778.801047321060
TARGET_YLLCORNER = 1484563.296254347777
TARGET_CELLSIZE = 250.000000000000

# Derived: top-left origin and affine transform for the fixed target grid
TARGET_TOP = TARGET_YLLCORNER + TARGET_NROWS * TARGET_CELLSIZE
TARGET_TRANSFORM = rasterio.transform.from_origin(
    TARGET_XLLCORNER, TARGET_TOP, TARGET_CELLSIZE, TARGET_CELLSIZE
)

# Maps texture class name -> pixel value in Soil_Texture.tif
# (Only classes present here have soil property data; others become NODATA)
TEXTURE_DICT = {
    'Clay': 1, 'Dyke and Ridges': 2, 'Gravelly Clay': 3, 'Habitation Mask': 4,
    'Loamy Sand': 5, 'Rock Outcrops': 6, 'Sandy Clay': 7, 'Sandy Clay Loam': 8,
    'Sandy Loam': 9, 'Water Body Mask': 10
}

# Property columns in the lookup table to process
PROPERTIES_ARITHMETIC = ["lambda_g", "lambda_a", "theta_fc", "theta_wp",
                          "theta_sat", "theta_awc", "psi_b", "rho_b", "theta_sat_rho"]
PROPERTY_GEOMETRIC = "ksat"   # aggregated via log-average (geometric mean)


# ----------------------------------------------------------------------
# STEP 1: Reclassify texture raster -> per-property rasters at native resolution
# ----------------------------------------------------------------------

def reclassify_properties():
    with rasterio.open(TEXTURE_TIF) as src:
        texture = src.read(1)
        profile = src.profile

    lut = pd.read_csv(LUT_CSV)
    lut = lut.dropna(subset=["Soil Texture"])                  # drop blank trailing rows
    lut["texture_ID"] = lut["Soil Texture"].map(TEXTURE_DICT)  # map name -> pixel value
    lut = lut.dropna(subset=["texture_ID"])                    # keep only mapped classes
    lut["texture_ID"] = lut["texture_ID"].astype(int)

    print("Classes being assigned properties:")
    print(lut[["Soil Texture", "texture_ID"]].to_string(index=False))

    all_props = PROPERTIES_ARITHMETIC + [PROPERTY_GEOMETRIC]

    out_profile = profile.copy()
    out_profile.update(dtype="float32", nodata=NODATA, count=1)

    for prop in all_props:
        out = np.full(texture.shape, NODATA, dtype=np.float32)
        for _, row in lut.iterrows():
            out[texture == row["texture_ID"]] = row[prop]

        n_valid = int(np.sum(out != NODATA))
        print(f"  {prop}: {n_valid}/{out.size} cells assigned "
              f"({100 * n_valid / out.size:.1f}%)")

        with rasterio.open(f"{WORK_DIR}/{prop}_native.tif", "w", **out_profile) as dst:
            dst.write(out, 1)


# ----------------------------------------------------------------------
# STEP 2: Aggregate native-resolution rasters to 250m
# ----------------------------------------------------------------------

def aggregate_to_250m(src_path, dst_path, nodata=NODATA):
    """Resample (average) onto the FIXED target grid (ncols/nrows/corner/cellsize
    defined above), so every output .asc lines up exactly with DRYP's other
    input grids (mask, DEM, etc.)."""
    with rasterio.open(src_path) as src:
        src_transform = src.transform
        src_crs = src.crs
        src_data = src.read(1)
        out_profile = src.profile.copy()

    dst_data = np.full((TARGET_NROWS, TARGET_NCOLS), nodata, dtype=np.float32)

    reproject(
        source=src_data,
        destination=dst_data,
        src_transform=src_transform,
        src_crs=src_crs,
        src_nodata=nodata,
        dst_transform=TARGET_TRANSFORM,
        dst_crs=src_crs,           # same CRS as source; only grid/resolution changes
        dst_nodata=nodata,
        resampling=Resampling.average,   # arithmetic mean of contributing source cells
    )

    out_profile.update(transform=TARGET_TRANSFORM, width=TARGET_NCOLS,
                        height=TARGET_NROWS, dtype="float32", nodata=nodata)

    with rasterio.open(dst_path, "w", **out_profile) as dst:
        dst.write(dst_data, 1)


def aggregate_all_properties():
    # Arithmetic-mean properties: aggregate directly
    for prop in PROPERTIES_ARITHMETIC:
        aggregate_to_250m(f"{WORK_DIR}/{prop}_native.tif",
                           f"{WORK_DIR}/{prop}_250m.tif")
        print(f"Aggregated {prop} -> 250m (arithmetic mean)")

    # ksat: log-transform -> average -> back-transform (geometric mean)
    # Needed because Ksat spans orders of magnitude; arithmetic mean would
    # overestimate effective conductivity at the coarser scale.
    prop = PROPERTY_GEOMETRIC
    with rasterio.open(f"{WORK_DIR}/{prop}_native.tif") as src:
        arr = src.read(1)
        prof = src.profile
    mask = arr != NODATA
    log_arr = np.where(mask, np.log(arr), NODATA).astype("float32")
    with rasterio.open(f"{WORK_DIR}/{prop}_log_native.tif", "w", **prof) as dst:
        dst.write(log_arr, 1)

    aggregate_to_250m(f"{WORK_DIR}/{prop}_log_native.tif",
                       f"{WORK_DIR}/{prop}_log_250m.tif")

    with rasterio.open(f"{WORK_DIR}/{prop}_log_250m.tif") as src:
        arr = src.read(1)
        prof = src.profile
    mask = arr != NODATA
    back = np.where(mask, np.exp(arr), NODATA).astype("float32")
    with rasterio.open(f"{WORK_DIR}/{prop}_250m.tif", "w", **prof) as dst:
        dst.write(back, 1)
    print(f"Aggregated {prop} -> 250m (geometric mean via log-average)")


# ----------------------------------------------------------------------
# STEP 3: Convert 250m GeoTIFFs to ESRI ASCII (.asc) grids
# ----------------------------------------------------------------------

def write_asc(tif_path, asc_path, nodata=NODATA):
    with rasterio.open(tif_path) as src:
        arr = src.read(1)

    # Use the FIXED target grid header values directly (not re-derived from the
    # raster) so every .asc matches DRYP's other inputs exactly, with no
    # float rounding drift.
    assert arr.shape == (TARGET_NROWS, TARGET_NCOLS), (
        f"{tif_path} has shape {arr.shape}, expected {(TARGET_NROWS, TARGET_NCOLS)}"
    )

    arr_out = np.where(np.isnan(arr), nodata, arr)

    with open(asc_path, "w") as f:
        f.write(f"ncols        {TARGET_NCOLS}\n")
        f.write(f"nrows        {TARGET_NROWS}\n")
        f.write(f"xllcorner    {TARGET_XLLCORNER:.12f}\n")
        f.write(f"yllcorner    {TARGET_YLLCORNER:.12f}\n")
        f.write(f"cellsize     {TARGET_CELLSIZE:.12f}\n")
        f.write(f"NODATA_value {int(nodata)}\n")
        for row in arr_out:
            f.write(" ".join(f"{v:.6g}" for v in row) + "\n")


def export_all_to_asc():
    all_props = PROPERTIES_ARITHMETIC + [PROPERTY_GEOMETRIC]
    for prop in all_props:
        tif_path = f"{WORK_DIR}/{prop}_250m.tif"
        asc_path = f"{OUT_DIR}/{prop}_250m.asc"
        write_asc(tif_path, asc_path)
        print(f"Wrote {asc_path}")

    # .asc has no CRS field -> keep a sidecar note
    with open(f"{OUT_DIR}/README_CRS.txt", "w") as f:
        f.write("CRS: EPSG:32643 (WGS 84 / UTM zone 43N)\n")
        f.write(f"Grid: ncols={TARGET_NCOLS}, nrows={TARGET_NROWS}, "
                f"cellsize={TARGET_CELLSIZE}\n")
        f.write(f"xllcorner={TARGET_XLLCORNER}, yllcorner={TARGET_YLLCORNER}\n")
        f.write(f"NODATA_value: {NODATA}\n\n")
        f.write("Source: Soil_Texture.tif reclassified to soil properties, then\n")
        f.write("resampled onto DRYP's fixed reference grid (arithmetic mean;\n")
        f.write("geometric mean for ksat) to match other DRYP input .asc files.\n")


# ----------------------------------------------------------------------
# RUN
# ----------------------------------------------------------------------

if __name__ == "__main__":
    print("=== Step 1: Reclassify texture -> properties (native resolution) ===")
    reclassify_properties()

    print("\n=== Step 2: Aggregate to 250m ===")
    aggregate_all_properties()

    print("\n=== Step 3: Export to .asc ===")
    export_all_to_asc()

    print("\nDone.")